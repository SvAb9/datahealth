-- Data-Health · 03 · Esquema clínico (pacientes, citas, órdenes, resultados)
-- Ejecutar conectado como DATAHEALTH, DESPUÉS de los scripts 01 y 02.
-- Ejecutar con "Ejecutar script" (F5).
--
-- Aislamiento por EPS (ADR-03) reforzado EN LA BASE DE DATOS:
-- las claves foráneas son compuestas (id_eps + id), así que es imposible
-- enlazar, por ejemplo, una cita de la EPS 1 con un paciente de la EPS 2.
--
-- Compatible con Oracle XE/Free, Oracle 19c+ y Autonomous Database (Azure/OCI).
-- No usa tablespaces, secuencias manuales ni funciones exclusivas de una edición.
-- Con ddl-auto=validate, las entidades Java deben coincidir con estas tablas.
-- =====================================================================

-- Necesario para las claves foráneas compuestas (id_eps, id_usuario).
ALTER TABLE usuario ADD CONSTRAINT uq_usuario_eps_id UNIQUE (id_eps, id_usuario);

-- ---------- PACIENTE (RF-06 a RF-11) ----------
-- id_usuario: enlaza al paciente con su usuario de rol PACIENTE (para "mi historia clínica").
-- El documento es único DENTRO de cada EPS (no global) para no revelar pacientes de otras EPS (RN-01).
CREATE TABLE paciente (
  id_paciente        NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  id_eps             NUMBER(19)         NOT NULL,
  id_usuario         NUMBER(19),
  documento          VARCHAR2(20 CHAR)  NOT NULL,
  nombre             VARCHAR2(255 CHAR) NOT NULL,
  edad               NUMBER(10)         NOT NULL,
  telefono           VARCHAR2(30 CHAR)  NOT NULL,
  direccion          VARCHAR2(255 CHAR),
  activo             NUMBER(1)          DEFAULT 1 NOT NULL,
  creado_por         NUMBER(19),
  fecha_creacion     TIMESTAMP(6)       NOT NULL,
  modificado_por     NUMBER(19),
  fecha_modificacion TIMESTAMP(6),
  CONSTRAINT pk_paciente         PRIMARY KEY (id_paciente),
  CONSTRAINT uq_paciente_eps_id  UNIQUE (id_eps, id_paciente),
  CONSTRAINT uq_paciente_eps_doc UNIQUE (id_eps, documento),
  CONSTRAINT uq_paciente_usuario UNIQUE (id_usuario),
  CONSTRAINT fk_paciente_eps     FOREIGN KEY (id_eps) REFERENCES eps (id_eps),
  CONSTRAINT fk_paciente_usuario FOREIGN KEY (id_eps, id_usuario) REFERENCES usuario (id_eps, id_usuario),
  CONSTRAINT ck_paciente_edad    CHECK (edad BETWEEN 0 AND 120),
  CONSTRAINT ck_paciente_activo  CHECK (activo IN (0, 1)),
  CONSTRAINT ck_paciente_doc     CHECK (REGEXP_LIKE(documento, '^[0-9]{5,15}$'))
);

-- ---------- CITA / ATENCIÓN (RF-16, RF-20, ADR-05) ----------
CREATE TABLE cita (
  id_cita            NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  id_eps             NUMBER(19)          NOT NULL,
  id_paciente        NUMBER(19)          NOT NULL,
  id_medico          NUMBER(19)          NOT NULL,
  fecha              TIMESTAMP(6)        NOT NULL,
  estado             VARCHAR2(20 CHAR)   DEFAULT 'ABIERTA' NOT NULL,
  diagnostico        VARCHAR2(2000 CHAR),
  observaciones      VARCHAR2(2000 CHAR),
  fecha_cierre       TIMESTAMP(6),
  cerrado_por        NUMBER(19),
  creado_por         NUMBER(19),
  fecha_creacion     TIMESTAMP(6)        NOT NULL,
  modificado_por     NUMBER(19),
  fecha_modificacion TIMESTAMP(6),
  CONSTRAINT pk_cita            PRIMARY KEY (id_cita),
  CONSTRAINT uq_cita_eps_id     UNIQUE (id_eps, id_cita),
  CONSTRAINT fk_cita_eps        FOREIGN KEY (id_eps) REFERENCES eps (id_eps),
  CONSTRAINT fk_cita_paciente   FOREIGN KEY (id_eps, id_paciente) REFERENCES paciente (id_eps, id_paciente),
  CONSTRAINT fk_cita_medico     FOREIGN KEY (id_eps, id_medico)   REFERENCES usuario (id_eps, id_usuario),
  CONSTRAINT fk_cita_cerrada_por FOREIGN KEY (cerrado_por) REFERENCES usuario (id_usuario),
  CONSTRAINT ck_cita_estado     CHECK (estado IN ('ABIERTA', 'CERRADA')),
  CONSTRAINT ck_cita_cierre     CHECK (
        (estado = 'ABIERTA' AND fecha_cierre IS NULL)
     OR (estado = 'CERRADA' AND fecha_cierre IS NOT NULL AND cerrado_por IS NOT NULL))
);

CREATE INDEX idx_cita_paciente_fecha ON cita (id_eps, id_paciente, fecha);
CREATE INDEX idx_cita_medico         ON cita (id_eps, id_medico);

-- ---------- CORRECCION_CITA (RF-21, ADR-05) ----------
-- Una corrección posterior al cierre es una NUEVA fila; la cita original no se toca.
CREATE TABLE correccion_cita (
  id_correccion NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  id_eps        NUMBER(19)          NOT NULL,
  id_cita       NUMBER(19)          NOT NULL,
  motivo        VARCHAR2(1000 CHAR) NOT NULL,
  detalle       VARCHAR2(2000 CHAR),
  id_usuario    NUMBER(19)          NOT NULL,
  fecha_hora    TIMESTAMP(6)        NOT NULL,
  CONSTRAINT pk_correccion_cita PRIMARY KEY (id_correccion),
  CONSTRAINT fk_correccion_cita FOREIGN KEY (id_eps, id_cita)    REFERENCES cita (id_eps, id_cita),
  CONSTRAINT fk_correccion_usr  FOREIGN KEY (id_eps, id_usuario) REFERENCES usuario (id_eps, id_usuario)
);

CREATE INDEX idx_correccion_cita ON correccion_cita (id_eps, id_cita);

-- ---------- EXAMEN_PACIENTE (RF-12: exámenes que el paciente trae a consulta) ----------
CREATE TABLE examen_paciente (
  id_examen      NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  id_eps         NUMBER(19)          NOT NULL,
  id_cita        NUMBER(19)          NOT NULL,
  nombre         VARCHAR2(255 CHAR)  NOT NULL,
  descripcion    VARCHAR2(1000 CHAR),
  fecha_examen   DATE,
  creado_por     NUMBER(19),
  fecha_creacion TIMESTAMP(6)        NOT NULL,
  CONSTRAINT pk_examen_paciente PRIMARY KEY (id_examen),
  CONSTRAINT fk_examen_cita     FOREIGN KEY (id_eps, id_cita) REFERENCES cita (id_eps, id_cita)
);

CREATE INDEX idx_examen_cita ON examen_paciente (id_eps, id_cita);

-- ---------- ORDEN (RF-13, RF-14, RF-15) ----------
-- tipo coincide con el frontend: MEDICA | MEDICAMENTO | LABORATORIO
CREATE TABLE orden (
  id_orden       NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  id_eps         NUMBER(19)          NOT NULL,
  id_cita        NUMBER(19)          NOT NULL,
  tipo           VARCHAR2(20 CHAR)   NOT NULL,
  descripcion    VARCHAR2(1000 CHAR) NOT NULL,
  creado_por     NUMBER(19),
  fecha_creacion TIMESTAMP(6)        NOT NULL,
  CONSTRAINT pk_orden          PRIMARY KEY (id_orden),
  CONSTRAINT uq_orden_eps_cita UNIQUE (id_eps, id_orden, id_cita),
  CONSTRAINT fk_orden_cita     FOREIGN KEY (id_eps, id_cita) REFERENCES cita (id_eps, id_cita),
  CONSTRAINT ck_orden_tipo     CHECK (tipo IN ('MEDICA', 'MEDICAMENTO', 'LABORATORIO'))
);

CREATE INDEX idx_orden_cita ON orden (id_eps, id_cita);

-- ---------- RESULTADO_EXAMEN (HU-07: pueden llegar después del cierre) ----------
-- La clave foránea (id_eps, id_orden, id_cita) garantiza que el resultado, su orden y su cita sean coherentes.
CREATE TABLE resultado_examen (
  id_resultado    NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  id_eps          NUMBER(19)          NOT NULL,
  id_orden        NUMBER(19)          NOT NULL,
  id_cita         NUMBER(19)          NOT NULL,
  resultado       VARCHAR2(2000 CHAR) NOT NULL,
  fecha_resultado TIMESTAMP(6)        NOT NULL,
  creado_por      NUMBER(19),
  fecha_creacion  TIMESTAMP(6)        NOT NULL,
  CONSTRAINT pk_resultado_examen PRIMARY KEY (id_resultado),
  CONSTRAINT fk_resultado_orden  FOREIGN KEY (id_eps, id_orden, id_cita) REFERENCES orden (id_eps, id_orden, id_cita)
);

CREATE INDEX idx_resultado_orden ON resultado_examen (id_eps, id_orden);
CREATE INDEX idx_resultado_cita  ON resultado_examen (id_eps, id_cita);